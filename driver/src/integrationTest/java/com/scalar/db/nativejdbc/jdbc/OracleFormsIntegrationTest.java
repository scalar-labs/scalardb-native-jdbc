  /**
   * 8. Not blocking, a measurement: the round trips of a block, as Oracle counts them ({@code
   * SQL*Net roundtrips to/from client} in {@code v$mystat}) and as the benchmark harness counts
   * them (the chunks the client sends through a local proxy, {@code DelayProxy.requests}): a plain
   * UPDATE; a block returning a ref cursor, its execute and the fetch of its row; a block returning
   * scalar OUT binds; a block returning its row through {@code DBMS_SQL.RETURN_RESULT}; each with
   * autocommit off (and the commit after) and on, where ojdbc may send the commit with the execute.
   * The design lists the one-round-trip autocommit as a follow-up; the cursor's fetch decides how
   * form 2 reads its row back.
   */
  @Test
  void roundTripsOfABlock() throws Exception {
    Matcher m = Pattern.compile("@(?://)?([^:/]+):(\\d+)[/:](.+)$").matcher(ORA.url());
    assertThat(m.find()).as(ORA.url()).isTrue();
    try (CountingProxy proxy = new CountingProxy(m.group(1), Integer.parseInt(m.group(2)));
        Connection c =
            DriverManager.getConnection(
                "jdbc:oracle:thin:@localhost:" + proxy.port() + "/" + m.group(3),
                ORA.username(),
                ORA.password())) {
      String refCursor =
          "DECLARE l_rows NUMBER := 0; l_x NUMBER; l_written NUMBER := 0; BEGIN"
              + " BEGIN SELECT 1, x INTO l_rows, l_x FROM ofa.m1 WHERE k = ?;"
              + " EXCEPTION WHEN NO_DATA_FOUND THEN NULL; END;"
              + " IF l_rows = 1 THEN UPDATE ofa.m1 SET x = x + 1 WHERE k = ?;"
              + " l_written := SQL%ROWCOUNT; END IF;"
              + " OPEN ? FOR SELECT l_rows, l_x, l_written FROM dual; END;";
      String scalars =
          "DECLARE l_rows NUMBER := 0; l_x NUMBER; l_written NUMBER := 0; BEGIN"
              + " BEGIN SELECT 1, x INTO l_rows, l_x FROM ofa.m1 WHERE k = ?;"
              + " EXCEPTION WHEN NO_DATA_FOUND THEN NULL; END;"
              + " IF l_rows = 1 THEN UPDATE ofa.m1 SET x = x + 1 WHERE k = ?;"
              + " l_written := SQL%ROWCOUNT; END IF;"
              + " ? := l_rows; ? := l_x; ? := l_written; END;";
      String implicitResult =
          "DECLARE l_rows NUMBER := 0; l_x NUMBER; l_written NUMBER := 0; l_c SYS_REFCURSOR; BEGIN"
              + " BEGIN SELECT 1, x INTO l_rows, l_x FROM ofa.m1 WHERE k = ?;"
              + " EXCEPTION WHEN NO_DATA_FOUND THEN NULL; END;"
              + " IF l_rows = 1 THEN UPDATE ofa.m1 SET x = x + 1 WHERE k = ?;"
              + " l_written := SQL%ROWCOUNT; END IF;"
              + " OPEN l_c FOR SELECT l_rows, l_x, l_written FROM dual;"
              + " DBMS_SQL.RETURN_RESULT(l_c); END;";
      for (boolean autocommit : List.of(false, true)) {
        c.setAutoCommit(autocommit);
        String mode = autocommit ? "autocommit on" : "autocommit off";
        Counter counter = new Counter(c, proxy);
        // warm up: the statements parsed once, the proxy's connection settled
        try (PreparedStatement ps = c.prepareStatement("UPDATE ofa.m1 SET x = x + 1 WHERE k = ?")) {
          ps.setInt(1, 1);
          ps.executeUpdate();
          counter.measure(
              "8 " + mode + ": a plain prepared UPDATE",
              () -> {
                ps.setInt(1, 1);
                ps.executeUpdate();
              });
        }
        try (CallableStatement cs = c.prepareCall(refCursor)) {
          cs.setInt(1, 1);
          cs.setInt(2, 1);
          cs.registerOutParameter(3, CURSOR);
          cs.execute();
          ((ResultSet) cs.getObject(3)).close();
          ResultSet[] out = new ResultSet[1];
          counter.measure(
              "8 " + mode + ": the block with a ref cursor OUT, execute",
              () -> {
                cs.setInt(1, 1);
                cs.setInt(2, 1);
                cs.registerOutParameter(3, CURSOR);
                cs.execute();
                out[0] = (ResultSet) cs.getObject(3);
              });
          counter.measure(
              "8 " + mode + ": ... and the fetch of its one row",
              () -> {
                assertThat(rows(out[0])).hasSize(1);
              });
        }
        try (CallableStatement cs = c.prepareCall(scalars)) {
          cs.setInt(1, 1);
          cs.setInt(2, 1);
          cs.registerOutParameter(3, java.sql.Types.NUMERIC);
          cs.registerOutParameter(4, java.sql.Types.NUMERIC);
          cs.registerOutParameter(5, java.sql.Types.NUMERIC);
          cs.execute();
          counter.measure(
              "8 " + mode + ": the block with three scalar OUT binds, execute and the values",
              () -> {
                cs.setInt(1, 1);
                cs.setInt(2, 1);
                cs.registerOutParameter(3, java.sql.Types.NUMERIC);
                cs.registerOutParameter(4, java.sql.Types.NUMERIC);
                cs.registerOutParameter(5, java.sql.Types.NUMERIC);
                cs.execute();
                assertThat(cs.getInt(3)).isEqualTo(1);
                assertThat(cs.getInt(5)).isEqualTo(1);
              });
        }
        String implicit =
            outcome(
                () -> {
                  try (CallableStatement cs = c.prepareCall(implicitResult)) {
                    cs.setInt(1, 1);
                    cs.setInt(2, 1);
                    cs.execute();
                    cs.getMoreResults();
                    rows(cs.getResultSet());
                    counter.measure(
                        "8 "
                            + mode
                            + ": the block returning its row by DBMS_SQL.RETURN_RESULT, execute"
                            + " and the row",
                        () -> {
                          cs.setInt(1, 1);
                          cs.setInt(2, 1);
                          cs.execute();
                          assertThat(cs.getMoreResults()).isTrue();
                          assertThat(rows(cs.getResultSet())).hasSize(1);
                        });
                    return 1;
                  }
                });
        if (!implicit.startsWith("ok")) {
          log("8 " + mode + ": DBMS_SQL.RETURN_RESULT through ojdbc: " + implicit);
        }
        if (!autocommit) {
          counter.measure("8 " + mode + ": the commit after a block", c::commit);
        }
      }
    }
  }

