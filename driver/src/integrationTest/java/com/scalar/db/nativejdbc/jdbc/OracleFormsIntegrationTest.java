  /**
   * 6. The restart of a waiting {@code SELECT ... FOR UPDATE} at READ COMMITTED, both layouts: A,
   * as a ScalarDB prepare would, updates a row and sets its metadata to state 1 in one transaction
   * and holds it; B's one-statement locking read of the design waits; A commits; B's row must show
   * state 1 (and, in the second case, a plain committed change's {@code tx_id} and version).
   * Decides: the inline one-statement form, whose failure is sent back (the design's premise would
   * be wrong); and the decoupled join form against its two round trips (a failure there is expected
   * as possible and selects the two statements). An extra: the gate's {@code NOT EXISTS} subquery
   * locks nothing on the metadata table.
   */
  @Test
  void restartOfAWaitingLock() throws Exception {
    ExecutorService pool = Executors.newSingleThreadExecutor();
    try (Connection a = ORA.open();
        Connection b = ORA.open()) {
      a.setAutoCommit(false);
      b.setAutoCommit(false);
      String inline =
          "SELECT t.k, t.x, t.tx_id, t.tx_version, t.tx_state FROM ofa.ri t WHERE t.k = 1"
              + " FOR UPDATE";
      // the driver's form: the join in a derived table, the data row alone locked through it
      String decoupled = rdLock("FOR UPDATE OF t.k");
      List<String> unsound = new ArrayList<>();
      for (String[] change :
          List.of(
              // a prepare: the data row changed, the metadata row in flight
              new String[] {"p", "P1", "1", "2", "1/p/P1/2/1"},
              // a driver write committed: the data row changed, the metadata row at a new version
              new String[] {"w", "W1", "3", "5", "1/w/W1/5/3"})) {
        for (boolean isInline : List.of(true, false)) {
          String layout = isInline ? "inline" : "decoupled";
          if (isInline) {
            ORA.execute(
                a,
                "UPDATE ofa.ri SET x = '"
                    + change[0]
                    + "', tx_id = '"
                    + change[1]
                    + "', tx_state = "
                    + change[2]
                    + ", tx_version = "
                    + change[3]
                    + " WHERE k = 1");
          } else {
            ORA.execute(
                a,
                "UPDATE ofa.rd SET x = '" + change[0] + "' WHERE k = 1",
                "UPDATE ofa.rd_meta SET tx_id = '"
                    + change[1]
                    + "', tx_state = "
                    + change[2]
                    + ", tx_version = "
                    + change[3]
                    + " WHERE k = 1");
          }
          Future<List<String>> lock = pool.submit(() -> query(b, isInline ? inline : decoupled));
          Thread.sleep(700);
          assertThat(lock.isDone()).as(layout + ": waits on the row").isFalse();
          a.commit();
          List<String> row = lock.get(30, TimeUnit.SECONDS);
          boolean sound = row.equals(List.of(change[4]));
          log(
              "6 "
                  + layout
                  + ", A commits "
                  + (change[2].equals("1") ? "a prepare" : "a write")
                  + " while B's lock waits: B's row "
                  + row
                  + (sound ? " (the newest)" : " (STALE)"));
          if (!sound) {
            unsound.add(layout + ": " + row + " for " + change[4]);
          }
          b.rollback();
          // back to the start
          if (isInline) {
            ORA.execute(
                a,
                "UPDATE ofa.ri SET x = 'a', tx_id = 'T0', tx_state = 3, tx_version = 1 WHERE k = 1");
          } else {
            ORA.execute(
                a,
                "UPDATE ofa.rd SET x = 'a' WHERE k = 1",
                "UPDATE ofa.rd_meta SET tx_id = 'T0', tx_state = 3, tx_version = 1 WHERE k = 1");
          }
          a.commit();
        }
      }
      // the extra: the gated lock at SNAPSHOT (form 5) locks nothing through its NOT EXISTS probe
      assertThat(
              query(
                  b,
                  "SELECT t.k FROM ofa.rd t WHERE t.k = 1 AND NOT EXISTS (SELECT /*+"
                      + " INDEX(m rd_meta_inflight) */ 1 FROM ofa.rd_meta m WHERE m.tx_state IN (1,"
                      + " 2)) FOR UPDATE"))
          .containsExactly("1");
      Future<Integer> meta =
          pool.submit(
              () -> {
                try (Statement st = a.createStatement()) {
                  return st.executeUpdate(
                      "UPDATE ofa.rd_meta SET tx_version = tx_version WHERE k = 1");
                }
              });
      assertThat(meta.get(10, TimeUnit.SECONDS)).as("the metadata row is not locked").isEqualTo(1);
      a.rollback();
      b.rollback();
      log(
          "6 extra: a FOR UPDATE with the gate's NOT EXISTS over the metadata table locks no metadata row");
      // the inline form's failure would fault the design's premise; the decoupled form's selects
      // its two statements: both are reported as failures here and sent back
      assertThat(unsound).as("B's row after the restart").isEmpty();
    } finally {
      pool.shutdownNow();
    }
  }

  /**
   * 6b. The scope of the decoupled form's lock (todo 334, design 4.3 "The locking read on Oracle"):
   * {@code FOR UPDATE} on the derived table of the join locks the metadata row with the data row,
   * which a write block, taking the data row first, deadlocks against (ORA-00060); {@code FOR
   * UPDATE OF t.k}, NOWAIT after it, locks the data row alone. Decides: the clause the driver emits
   * on a decoupled table.
   */
  @Test
  void scopeOfTheDecoupledLock() throws Exception {
    try (Connection a = ORA.open();
        Connection b = ORA.open()) {
      a.setAutoCommit(false);
      b.setAutoCommit(false);
      for (String clause : List.of("FOR UPDATE", "FOR UPDATE OF t.k", "FOR UPDATE OF t.k NOWAIT")) {
        assertThat(query(a, rdLock(clause))).containsExactly("1/a/T0/1/3");
        boolean meta = locked(b, "SELECT k FROM ofa.rd_meta WHERE k = 1 FOR UPDATE NOWAIT");
        boolean data = locked(b, "SELECT k FROM ofa.rd WHERE k = 1 FOR UPDATE NOWAIT");
        log("6b " + clause + ": the metadata row locked " + meta + ", the data row " + data);
        assertThat(data).as(clause + ": the data row").isTrue();
        assertThat(meta).as(clause + ": the metadata row").isEqualTo(clause.equals("FOR UPDATE"));
        a.rollback();
        b.rollback();
      }
    }
  }

  /** The decoupled form of test 6 on {@code ofa.rd}, as the driver emits it, with a clause. */
  private static String rdLock(String clause) {
    return "SELECT k, x, v0, v1, v2 FROM (SELECT t.k, t.x, m.tx_id AS v0, m.tx_version AS v1,"
        + " m.tx_state AS v2 FROM ofa.rd t LEFT JOIN ofa.rd_meta m ON m.k = t.k) t WHERE k = 1 "
        + clause;
  }

  /** Whether a {@code FOR UPDATE NOWAIT} meets a lock: ORA-00054. */
  private static boolean locked(Connection c, String sql) throws SQLException {
    try {
      query(c, sql);
      return false;
    } catch (SQLException e) {
      if (e.getErrorCode() != 54) {
        throw e;
      }
      return true;
    }
  }

