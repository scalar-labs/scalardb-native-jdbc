  /** Round trips as Oracle counts them for this session, and chunks as the proxy counts them. */
  private static final class Counter {
    private final Connection c;
    private final CountingProxy proxy;
    private final long statCost;

    Counter(Connection c, CountingProxy proxy) throws SQLException {
      this.c = c;
      this.proxy = proxy;
      long first = roundTrips();
      long second = roundTrips();
      this.statCost = second - first; // what reading the statistic itself costs, 1 as a rule
    }

    private long roundTrips() throws SQLException {
      try (Statement st = c.createStatement();
          ResultSet rs =
              st.executeQuery(
                  "SELECT s.value FROM v$mystat s JOIN v$statname n ON n.statistic# = s.statistic#"
                      + " WHERE n.name = 'SQL*Net roundtrips to/from client'")) {
        assertThat(rs.next()).isTrue();
        return rs.getLong(1);
      }
    }

    void measure(String label, SqlRunnable action) throws Exception {
      long trips = roundTrips();
      long chunks = proxy.requests.get();
      action.run();
      long tripsAfter = roundTrips();
      long chunksAfter = proxy.requests.get();
      log(
          label
              + ": "
              + (tripsAfter - trips - statCost)
              + " round trip(s) by v$mystat, "
              + (chunksAfter - chunks - statCost)
              + " client chunk(s) by the proxy");
    }
  }

  /** A TCP forwarder counting the chunks the client sends, as the harness's DelayProxy counts. */
  private static final class CountingProxy implements AutoCloseable {
    private final ServerSocket server;
    final AtomicLong requests = new AtomicLong();

    CountingProxy(String host, int port) throws IOException {
      server = new ServerSocket();
      server.bind(new InetSocketAddress(InetAddress.getLoopbackAddress(), 0));
      Thread accept =
          new Thread(
              () -> {
                while (!server.isClosed()) {
                  try {
                    Socket client = server.accept();
                    Socket db = new Socket(host, port);
                    client.setTcpNoDelay(true);
                    db.setTcpNoDelay(true);
                    pipe(client.getInputStream(), db.getOutputStream(), true);
                    pipe(db.getInputStream(), client.getOutputStream(), false);
                  } catch (IOException e) {
                    // closed
                  }
                }
              });
      accept.setDaemon(true);
      accept.start();
    }

    int port() {
      return server.getLocalPort();
    }

    private void pipe(InputStream in, OutputStream out, boolean fromClient) {
      Thread t =
          new Thread(
              () -> {
                byte[] buf = new byte[65536];
                try {
                  for (int n; (n = in.read(buf)) > 0; ) {
                    if (fromClient) {
                      requests.incrementAndGet();
                    }
                    out.write(buf, 0, n);
                    out.flush();
                  }
                } catch (IOException e) {
                  // closed
                }
                try {
                  out.close();
                } catch (IOException e) {
                  // closed
                }
              });
      t.setDaemon(true);
      t.start();
    }

    @Override
    public void close() throws IOException {
      server.close();
    }
  }

  @FunctionalInterface
  private interface SqlRunnable {
    void run() throws Exception;
  }

  @FunctionalInterface
  private interface SqlSupplier<T> {
    T get() throws Exception;
  }

  @FunctionalInterface
  private interface Binder {
    void bind(CallableStatement cs) throws SQLException;
  }

  /** Runs a block whose last bind is a cursor OUT, and returns the cursor's one row. */
  private static String cursorRow(Connection c, String block, Binder binder) throws SQLException {
    try (CallableStatement cs = c.prepareCall(block)) {
      binder.bind(cs);
      int cursor = (int) block.chars().filter(ch -> ch == '?').count();
      cs.registerOutParameter(cursor, CURSOR);
      cs.execute();
      try (ResultSet rs = (ResultSet) cs.getObject(cursor)) {
        List<String> rows = rows(rs);
        assertThat(rows).hasSize(1);
        return rows.get(0);
      }
    }
  }

  private static List<String> query(Connection c, String sql) throws SQLException {
    try (Statement st = c.createStatement()) {
      return rows(st.executeQuery(sql));
    }
  }

  private static SQLException fails(SqlRunnable action) throws Exception {
    try {
      action.run();
    } catch (SQLException e) {
      return e;
    }
    return fail("expected an SQLException");
  }

  /** What an action gave: {@code ok <value>} or the error's code and first line. */
  private static String outcome(SqlSupplier<?> action) {
    try {
      return "ok " + action.get();
    } catch (SQLException e) {
      return "ORA-" + e.getErrorCode() + " (SQLState " + e.getSQLState() + "): " + line(e);
    } catch (Exception e) {
      return e.getClass().getSimpleName() + ": " + e.getMessage();
    }
  }

  private static String line(Throwable e) {
    String m = String.valueOf(e.getMessage()).strip();
    int nl = m.indexOf('\n');
    return nl < 0 ? m : m.substring(0, nl);
  }

  private static String typeOf(ResultSetMetaData md, int column) throws SQLException {
    return md.getColumnTypeName(column) + "(" + md.getColumnType(column) + ")";
  }

  private static String show(@Nullable Object v) {
    if (v == null) {
      return "null";
    }
    if (v instanceof byte[] bytes) {
      return "bytes" + Arrays.toString(bytes);
    }
    return v + " (" + v.getClass().getSimpleName() + ")";
  }
