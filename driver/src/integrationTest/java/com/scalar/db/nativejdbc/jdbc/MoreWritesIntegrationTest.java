  private static void batches(
      Engines e, DistributedTransactionManager tm, TwoPhaseCommitTransactionManager tpc, Table t)
      throws Exception {
    try (Connection d = e.openDriver()) {
      // a prepared batch in autocommit: one transaction, a count per entry
      try (PreparedStatement ps =
          d.prepareStatement("INSERT INTO " + t.sql + " (id, x) VALUES (?, ?)")) {
        for (int id = 10; id < 13; id++) {
          ps.setInt(1, id);
          ps.setString(2, "b" + id);
          ps.addBatch();
        }
        assertThat(ps.executeBatch()).containsExactly(1, 1, 1);
        assertThat(ps.getUpdateCount()).isEqualTo(-1);
        // the batch was cleared when it ran
        assertThat(ps.executeBatch()).isEmpty();
      }
      try (PreparedStatement ps =
          d.prepareStatement("UPDATE " + t.sql + " SET x = CONCAT(x, ?) WHERE id >= ?")) {
        ps.setString(1, "!");
        ps.setInt(2, 12);
        ps.addBatch();
        ps.setString(1, "?");
        ps.setInt(2, 99);
        ps.addBatch();
        assertThat(ps.executeLargeBatch()).containsExactly(1L, 0L);
      }
      // a statement batch: ScalarDB writes and a plain table's, in order
      Statement st = d.createStatement();
      st.addBatch("INSERT INTO wb.plain VALUES (1, 'p')");
      st.addBatch("DELETE FROM " + t.sql + " WHERE id = 10");
      st.addBatch("UPDATE wb.plain SET x = 'q' WHERE id = 1");
      assertThat(st.executeBatch()).containsExactly(1, 1, 1);
      assertThat(rows(d, "SELECT id, x FROM " + t.sql + " WHERE id >= 10 ORDER BY id"))
          .containsExactly("11/b11", "12/b12!");
      assertThat(rows(d, "SELECT x FROM wb.plain")).containsExactly("q");
      d.createStatement().executeUpdate("DELETE FROM wb.plain");
      // more entries than PostgreSQL sends together (todo 329), each seeing the ones before it
      try (PreparedStatement ps =
          d.prepareStatement("INSERT INTO " + t.sql + " (id, x) VALUES (?, ?)")) {
        for (int id = 40; id < 60; id++) {
          ps.setInt(1, id);
          ps.setString(2, "t");
          ps.addBatch();
        }
        assertThat(ps.executeBatch()).hasSize(20).containsOnly(1);
      }
      Statement chain = d.createStatement();
      chain.addBatch("UPDATE " + t.sql + " SET x = 'u' WHERE id = 40");
      chain.addBatch("UPDATE " + t.sql + " SET x = 'v' WHERE x = 'u'");
      chain.addBatch("DELETE FROM " + t.sql + " WHERE id = 41");
      // the deleted key again: its tombstone is taken over, which runs the entries one by one
      chain.addBatch("INSERT INTO " + t.sql + " (id, x) VALUES (41, 'w')");
      chain.addBatch("UPDATE " + t.sql + " SET x = 'z' WHERE id = 99");
      assertThat(chain.executeBatch()).containsExactly(1, 1, 1, 1, 0);
      assertThat(rows(d, "SELECT id, x FROM " + t.sql + " WHERE id IN (40, 41, 59) ORDER BY id"))
          .containsExactly("40/v", "41/w", "59/t");
      // in a transaction: a duplicate late in a batch, the counts of the entries before it
      d.setAutoCommit(false);
      try (PreparedStatement ps =
          d.prepareStatement("UPDATE " + t.sql + " SET x = ? WHERE id = ?")) {
        for (int id = 40; id < 60; id++) {
          ps.setString(1, "s");
          ps.setInt(2, id);
          ps.addBatch();
        }
        assertThat(ps.executeBatch()).hasSize(20).containsOnly(1);
      }
      try (PreparedStatement ps =
          d.prepareStatement("INSERT INTO " + t.sql + " (id, x) VALUES (?, 'd')")) {
        for (int id = 60; id < 80; id++) {
          ps.setInt(1, id == 78 ? 45 : id);
          ps.addBatch();
        }
        assertThatThrownBy(ps::executeBatch)
            .isInstanceOfSatisfying(
                BatchUpdateException.class,
                b -> {
                  assertThat(b.getUpdateCounts()).hasSize(18).containsOnly(1);
                  assertThat(e.engine().isDuplicateKey(b.getNextException())).isTrue();
                });
      }
      d.rollback();
      d.setAutoCommit(true);
      assertThat(rows(d, "SELECT COUNT(*) FROM " + t.sql + " WHERE x = 's' OR x = 'd'"))
          .containsExactly("0");
      if (e.engine() == Engine.POSTGRESQL) {
        // a failed statement ends PostgreSQL's transaction: a later batch is refused, not undone
        // to an earlier batch's savepoint and run (todo 329)
        d.setAutoCommit(false);
        try (PreparedStatement ps =
            d.prepareStatement("INSERT INTO " + t.sql + " (id, x) VALUES (?, 'k')")) {
          for (int id = 80; id < 83; id++) {
            ps.setInt(1, id);
            ps.addBatch();
          }
          assertThat(ps.executeBatch()).containsExactly(1, 1, 1);
          assertThatThrownBy(() -> d.createStatement().executeQuery("SELECT 1 / 0"))
              .isInstanceOf(SQLException.class);
          for (int id = 83; id < 86; id++) {
            ps.setInt(1, id);
            ps.addBatch();
          }
          // refused by the batch's planning here, or by its savepoint where it is planned already
          assertThatThrownBy(ps::executeBatch)
              .isInstanceOf(SQLException.class)
              .extracting("SQLState")
              .isEqualTo("25P02");
        }
        d.rollback();
        d.setAutoCommit(true);
        assertThat(rows(d, "SELECT COUNT(*) FROM " + t.sql + " WHERE id >= 80"))
            .containsExactly("0");
        // the savepoint a batch leaves set to the next one stays below the application's, which
        // the next batch's release would release too (todo 329)
        d.setAutoCommit(false);
        try (PreparedStatement ps =
            d.prepareStatement("INSERT INTO " + t.sql + " (id, x) VALUES (?, 'k')")) {
          twoEntries(ps, 80);
          Savepoint mine = d.setSavepoint();
          twoEntries(ps, 82); // undone
          d.rollback(mine);
          Statement sql = d.createStatement();
          sql.execute("SAVEPOINT mine");
          twoEntries(ps, 84); // undone
          sql.execute("ROLLBACK TO SAVEPOINT mine");
          Savepoint again = d.setSavepoint();
          twoEntries(ps, 86);
          d.releaseSavepoint(again);
          twoEntries(ps, 88);
          d.commit();
        }
        d.setAutoCommit(true);
        assertThat(rows(d, "SELECT id FROM " + t.sql + " WHERE id >= 80 ORDER BY id"))
            .containsExactly("80", "81", "86", "87", "88", "89");
        d.createStatement().executeUpdate("DELETE FROM " + t.sql + " WHERE id >= 80");
        // pgjdbc's autosave: entries one at a time, a savepoint of its own before each
        Properties autosave = new Properties();
        autosave.setProperty("autosave", "always");
        try (Connection a = e.openDriver(autosave)) {
          a.setAutoCommit(false);
          try (PreparedStatement ps =
              a.prepareStatement("INSERT INTO " + t.sql + " (id, x) VALUES (?, 'a')")) {
            for (int id = 80; id < 83; id++) {
              ps.setInt(1, id);
              ps.addBatch();
            }
            assertThat(ps.executeBatch()).containsExactly(1, 1, 1);
          }
          a.commit();
        }
        assertThat(rows(d, "SELECT COUNT(*) FROM " + t.sql + " WHERE id >= 80 AND x = 'a'"))
            .containsExactly("3");
        d.createStatement().executeUpdate("DELETE FROM " + t.sql + " WHERE id >= 80");
        mergedBatches(e, tm, tpc, t, d);
      }
      d.createStatement().executeUpdate("DELETE FROM " + t.sql + " WHERE id >= 40");
      // a failure in autocommit undoes the whole batch; the counts before it, the cause next
      try (PreparedStatement ps =
          d.prepareStatement("INSERT INTO " + t.sql + " (id, x) VALUES (?, 'f')")) {
        ps.setInt(1, 20);
        ps.addBatch();
        ps.setInt(1, 1);
        ps.addBatch();
        ps.setInt(1, 21);
        ps.addBatch();
        assertThatThrownBy(ps::executeBatch)
            .isInstanceOfSatisfying(
                BatchUpdateException.class,
                b -> {
                  assertThat(b.getUpdateCounts()).containsExactly(1);
                  assertThat(e.engine().isDuplicateKey(b.getNextException())).isTrue();
                  assertThat(b.getSQLState())
                      .isEqualTo(e.engine() == Engine.POSTGRESQL ? "23505" : "23000");
                });
      }
      assertThat(rows(d, "SELECT COUNT(*) FROM " + t.sql + " WHERE id >= 20")).containsExactly("0");
      // in a transaction a batch is part of it: rolled back with it
      d.setAutoCommit(false);
      try (PreparedStatement ps = d.prepareStatement("DELETE FROM " + t.sql + " WHERE id = ?")) {
        ps.setInt(1, 11);
        ps.addBatch();
        ps.setInt(1, 12);
        ps.addBatch();
        assertThat(ps.executeBatch()).containsExactly(1, 1);
      }
      d.rollback();
      assertThat(rows(d, "SELECT COUNT(*) FROM " + t.sql + " WHERE id >= 10")).containsExactly("2");
      // an entry on a row ScalarDB holds prepared aborts the batch, and the transaction
      TwoPhaseCommitTransaction held = tpc.begin();
      held.update(
          Update.newBuilder()
              .namespace(N("wb"))
              .table(t.scalarDbName)
              .partitionKey(id(2))
              .textValue(N("x"), "held")
              .build());
      held.prepare();
      try {
        Statement batch = d.createStatement();
        batch.addBatch("UPDATE " + t.sql + " SET x = 'w' WHERE id = 1");
        batch.addBatch("UPDATE " + t.sql + " SET x = 'w' WHERE id = 2");
        assertThatThrownBy(batch::executeBatch)
            .isInstanceOfSatisfying(
                BatchUpdateException.class,
                b -> {
                  assertThat(b.getUpdateCounts()).containsExactly(1);
                  assertThat(b.getSQLState()).isEqualTo("40001");
                  assertThat((Throwable) b.getNextException())
                      .isInstanceOf(SQLTransactionRollbackException.class);
                });
        assertThatThrownBy(d::commit).isInstanceOf(SQLTransactionRollbackException.class);
        d.rollback();
      } finally {
        held.rollback();
      }
      d.setAutoCommit(true);
    }
    // ScalarDB reads the batch's writes as committed values
    assertThat(scalarDbX(tm, t, 11)).contains("b11");
    assertThat(scalarDbX(tm, t, 12)).contains("b12!");
    assertThat(scalarDbX(tm, t, 10)).isEmpty();
    assertThat(scalarDbX(tm, t, 1)).contains("a");
  }

  /**
   * A prepared batch of writes by key on PostgreSQL, its entries as one statement (todo 329): the
   * same outcomes and counts as one by one, two entries on one key and a row in flight among them.
   */
  private static void mergedBatches(
      Engines e,
      DistributedTransactionManager tm,
      TwoPhaseCommitTransactionManager tpc,
      Table t,
      Connection d)
      throws Exception {
    try (PreparedStatement ins =
        d.prepareStatement("INSERT INTO " + t.sql + " (id, x) VALUES (?, 'm')")) {
      for (int id = 90; id < 96; id++) {
        ins.setInt(1, id);
        ins.addBatch();
      }
      assertThat(ins.executeBatch()).hasSize(6).containsOnly(1);
    }
    d.setAutoCommit(false);
    try (PreparedStatement ps =
        d.prepareStatement("UPDATE " + t.sql + " SET x = CONCAT(x, ?) WHERE id = ?")) {
      // each entry its own values; a key with no row counts 0
      int[][] entries = {{90, 1}, {91, 2}, {99, 3}, {92, 4}};
      for (int[] entry : entries) {
        ps.setString(1, String.valueOf(entry[1]));
        ps.setInt(2, entry[0]);
        ps.addBatch();
      }
      assertThat(ps.executeBatch()).containsExactly(1, 1, 0, 1);
      // two entries on one key: the second sees the first's write, as one by one
      for (String s : List.of("a", "b")) {
        ps.setString(1, s);
        ps.setInt(2, 93);
        ps.addBatch();
      }
      assertThat(ps.executeBatch()).containsExactly(1, 1);
    }
    d.commit();
    assertThat(rows(d, "SELECT id, x FROM " + t.sql + " WHERE id BETWEEN 90 AND 93 ORDER BY id"))
        .containsExactly("90/m1", "91/m2", "92/m4", "93/mab");
    // a row this transaction read, changed by ScalarDB before the batch: first-updater-wins
    assertThat(rows(d, "SELECT x FROM " + t.sql + " WHERE id = 94")).containsExactly("m");
    DistributedTransaction other = tm.begin();
    other.update(
        Update.newBuilder()
            .namespace(N("wb"))
            .table(t.scalarDbName)
            .partitionKey(id(94))
            .textValue(N("x"), "s")
            .build());
    other.commit();
    try (PreparedStatement ps = d.prepareStatement("UPDATE " + t.sql + " SET x = ? WHERE id = ?")) {
      for (int id : new int[] {95, 94}) {
        ps.setString(1, "late");
        ps.setInt(2, id);
        ps.addBatch();
      }
      assertThatThrownBy(ps::executeBatch)
          .isInstanceOfSatisfying(
              BatchUpdateException.class, b -> assertThat(b.getSQLState()).isEqualTo("40001"));
    }
    d.rollback();
    // a key a ScalarDB transaction holds prepared aborts the batch
    TwoPhaseCommitTransaction held = tpc.begin();
    held.update(
        Update.newBuilder()
            .namespace(N("wb"))
            .table(t.scalarDbName)
            .partitionKey(id(95))
            .textValue(N("x"), "held")
            .build());
    held.prepare();
    try (PreparedStatement ps = d.prepareStatement("UPDATE " + t.sql + " SET x = ? WHERE id = ?")) {
      for (int id : new int[] {94, 95}) {
        ps.setString(1, "w");
        ps.setInt(2, id);
        ps.addBatch();
      }
      assertThatThrownBy(ps::executeBatch)
          .isInstanceOfSatisfying(
              BatchUpdateException.class, b -> assertThat(b.getSQLState()).isEqualTo("40001"));
      d.rollback();
    } finally {
      held.rollback();
    }
    // a DELETE by key, a key with no row among them
    try (PreparedStatement ps = d.prepareStatement("DELETE FROM " + t.sql + " WHERE id = ?")) {
      for (int id : new int[] {94, 98, 95}) {
        ps.setInt(1, id);
        ps.addBatch();
      }
      assertThat(ps.executeBatch()).containsExactly(1, 0, 1);
    }
    d.commit();
    d.setAutoCommit(true);
    assertThat(rows(d, "SELECT id FROM " + t.sql + " WHERE id BETWEEN 90 AND 99 ORDER BY id"))
        .containsExactly("90", "91", "92", "93");
    assertThat(scalarDbX(tm, t, 93)).contains("mab");
    assertThat(scalarDbX(tm, t, 94)).isEmpty();
    // an INSERT of a key whose delete left a tombstone, among others: taken over, as one by one
    try (PreparedStatement ins =
        d.prepareStatement("INSERT INTO " + t.sql + " (id, x) VALUES (?, ?)")) {
      for (int id : new int[] {96, 94, 97}) {
        ins.setInt(1, id);
        ins.setString(2, "n" + id);
        ins.addBatch();
      }
      assertThat(ins.executeBatch()).containsExactly(1, 1, 1);
    }
    assertThat(rows(d, "SELECT id, x FROM " + t.sql + " WHERE id IN (94, 96, 97) ORDER BY id"))
        .containsExactly("94/n94", "96/n96", "97/n97");
    assertThat(scalarDbX(tm, t, 94)).contains("n94");
    // a batch whose entry lacks a value fails before it is sent: the next batch of the transaction
    // does not release a savepoint the first never set
    d.setAutoCommit(false);
    try (PreparedStatement ps = d.prepareStatement("UPDATE " + t.sql + " SET x = ? WHERE id = ?")) {
      ps.setString(1, "p");
      ps.setInt(2, 90);
      ps.addBatch();
      ps.clearParameters();
      ps.setInt(2, 91);
      ps.addBatch();
      assertThatThrownBy(ps::executeBatch).isInstanceOf(SQLException.class);
      for (int id : new int[] {90, 91}) {
        ps.setString(1, "q");
        ps.setInt(2, id);
        ps.addBatch();
      }
      assertThat(ps.executeBatch()).containsExactly(1, 1);
    }
    d.commit();
    assertThat(rows(d, "SELECT x FROM " + t.sql + " WHERE id IN (90, 91) ORDER BY id"))
        .containsExactly("q", "q");
    // a metadata row in a state other than in flight or committed is no committed image: a write by
    // its key counts 0 and writes nothing, as the fused statement does
    try (Connection v = e.open();
        Statement s = v.createStatement()) {
      assertThat(s.executeUpdate("UPDATE " + t.meta + " SET tx_state = 4 WHERE id = 92"))
          .isEqualTo(1);
    }
    try (PreparedStatement ps = d.prepareStatement("UPDATE " + t.sql + " SET x = ? WHERE id = ?")) {
      ps.setString(1, "r");
      ps.setInt(2, 92);
      assertThat(ps.executeUpdate()).isZero();
    }
    d.rollback();
    assertThat(rows(d, "SELECT x FROM " + t.sql + " WHERE id = 92")).containsExactly("m4");
    d.setAutoCommit(true);
    try (Connection v = e.open();
        Statement s = v.createStatement()) {
      s.executeUpdate("UPDATE " + t.meta + " SET tx_state = 3 WHERE id = 92");
    }
    d.createStatement().executeUpdate("DELETE FROM " + t.sql + " WHERE id >= 90");
  }

