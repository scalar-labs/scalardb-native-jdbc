  /**
   * The review of 8c1 (254): mssql-jdbc binds a time read back as datetime, which no time equals.
   */
  private static void timeKeys(Engines e) throws Exception {
    try (Connection d = e.openDriver();
        Statement s = d.createStatement()) {
      assertThat(s.executeUpdate("INSERT INTO wb.tk VALUES ('10:00:00.000001', 1)")).isEqualTo(1);
      assertThat(s.executeUpdate("UPDATE wb.tk SET x = 2 WHERE k = '09:00:00.123456'"))
          .isEqualTo(1);
      assertThat(s.executeUpdate("DELETE FROM wb.tk WHERE k = '10:00:00.000001'")).isEqualTo(1);
      assertThat(rows(d, "SELECT x FROM wb.tk")).containsExactly("2");
    }
  }

  /** The review of 8d1 on Oracle (todos 275-277). */
  private static void reviewOf8d1(Engines e) throws Exception {
    try (Connection d = e.openDriver();
        Statement st = d.createStatement()) {
      // 282: DUAL, a public synonym of a table ScalarDB does not manage
      assertThat(rows(d, "SELECT 1 FROM dual")).containsExactly("1");
      // 275: a COMPOUND trigger may change the key as a BEFORE one may: refused
      assertThatThrownBy(() -> st.executeUpdate("INSERT INTO wb.ct (k, x) VALUES (5, 1)"))
          .isInstanceOf(SQLFeatureNotSupportedException.class);
      // 277: a CHAR key bound as a string, read back padded; a text key bound as a number
      try (PreparedStatement ps = d.prepareStatement("INSERT INTO wb.ch (k, x) VALUES (?, 0)")) {
        ps.setString(1, "a");
        assertThat(ps.executeUpdate()).isEqualTo(1);
      }
      e.execute(d, "INSERT INTO wb.vk (k, x) VALUES ('abc', 0)");
      try (PreparedStatement ps = d.prepareStatement("INSERT INTO wb.vk (k, x) VALUES (?, 0)")) {
        ps.setInt(1, 7);
        assertThat(ps.executeUpdate()).isEqualTo(1);
      }
      // 278: a lower-case IDENTITY key, generated, and given as 0, which Oracle stores as it is
      assertThat(st.executeUpdate("INSERT INTO wb.lq (x) VALUES ('g')")).isEqualTo(1);
      assertThat(st.executeUpdate("INSERT INTO wb.lq (\"id\", x) VALUES (0, 'z')")).isEqualTo(1);
      assertThat(rows(d, "SELECT x FROM wb.lq WHERE \"id\" = 0")).containsExactly("z");
      // several rows that leave the IDENTITY key out, whose keys Oracle does not return: refused
      assertThatThrownBy(() -> st.executeUpdate("INSERT INTO wb.lq (x) VALUES ('m'), ('n')"))
          .isInstanceOf(SQLFeatureNotSupportedException.class);
      // FOR UPDATE OF a column the read does not select
      d.setAutoCommit(false);
      assertThat(rows(d, "SELECT id FROM wb.imp WHERE id = 1 FOR UPDATE OF x"))
          .containsExactly("1");
      d.rollback();
      d.setAutoCommit(true);
    }
    // 276: a duplicate is told in any language the session's messages are in, as ojdbc sets it
    // from the JVM's locale
    try (Connection d = e.openDriver();
        Statement st = d.createStatement()) {
      st.execute("ALTER SESSION SET NLS_LANGUAGE = GERMAN");
      assertThatThrownBy(() -> st.executeUpdate("INSERT INTO wb.imp (id, x) VALUES (1, 'z')"))
          .isInstanceOf(SQLException.class)
          .satisfies(ex -> assertThat(ex.getMessage()).doesNotContain("constraint ("))
          .extracting("SQLState")
          .isEqualTo("23000");
    }
  }

  /** SQL Server's table hints (design 4.7): locking ones as the locking read, others refused. */
  private static void tableHints(Engines e) throws Exception {
    try (Connection d = e.openDriver();
        Connection v = e.open()) {
      e.execute(v, "INSERT INTO wb.plain VALUES (1, 'p')");
      // a dirty read of a ScalarDB table, however the hint is written; without WITH the parser
      // would read a function, naming no table; a carriage return ends a line comment, and SQL
      // Server reads a zero-width space as whitespace
      for (String hinted :
          List.of(
              "wb.imp (NOLOCK)",
              "wb.imp a (NOLOCK)",
              "wb.imp WITH (NOLOCK)",
              "wb.imp WITH (READUNCOMMITTED)",
              "wb.imp WITH (ROWLOCK, READUNCOMMITTED)",
              "wb.imp --c\r(NOLOCK)",
              "wb.imp\u200B",
              "wb.imp\u200B(NOLOCK)")) {
        assertRefused(() -> rows(d, "SELECT x FROM " + hinted + " WHERE id = 1"));
      }
      // FOR UPDATE is not T-SQL; nor does a write take a hint
      assertRefused(
          () -> d.createStatement().executeQuery("SELECT x FROM wb.imp WHERE id = 1 FOR UPDATE"));
      assertRefused(
          () ->
              d.createStatement()
                  .executeUpdate("UPDATE wb.imp WITH (ROWLOCK) SET x = 'h' WHERE id = 1"));
      // a hint without a lock is read as it is
      assertThat(rows(d, "SELECT x FROM wb.imp WITH (ROWLOCK) WHERE id = 1")).containsExactly("a");
      // another table's hint stays in a statement the driver does not rewrite, and is refused in
      // one it does, which would lose it
      d.setAutoCommit(false);
      assertThat(rows(d, "SELECT x FROM wb.plain WITH (UPDLOCK) WHERE id = 1"))
          .containsExactly("p");
      assertRefused(
          () ->
              rows(
                  d,
                  "SELECT p.x FROM wb.plain p WITH (UPDLOCK) JOIN wb.imp i ON i.id = p.id"
                      + " WHERE p.id = 1"));
      d.rollback();
      // T-SQL's transaction statements are refused: the JDBC methods carry them
      assertRefused(() -> d.createStatement().execute("BEGIN TRANSACTION"));
      d.setAutoCommit(true);
    }
    // 259: XACT_ABORT on for every session, as a server option: the driver does not connect
    try (Connection v = e.open();
        Statement s = v.createStatement()) {
      s.execute("EXEC sp_configure 'user options', 16384; RECONFIGURE");
      try {
        assertThatThrownBy(() -> e.openDriver().close())
            .isInstanceOf(SQLException.class)
            .hasMessageContaining("XACT_ABORT");
      } finally {
        s.execute("EXEC sp_configure 'user options', 0; RECONFIGURE");
      }
    }
  }

  /** The findings of the review of milestone 8a (todos 186-199). */
  private static void reviewOf8a(Engines e, Catalog catalog) throws Exception {
    Engine engine = e.engine();
    boolean mysql = engine == Engine.MYSQL;
    String ordMeta = "wb." + Q(catalog.lookup(List.of(), N("wb"), N("ord")).metadataTable());
    String vkMeta = "wb." + Q(catalog.lookup(List.of(), N("wb"), N("vk")).metadataTable());
    try (Connection d = e.openDriver();
        Connection v = e.open()) {
      // 188, 203: without a column list the key's position is the table's, not ScalarDB's
      assertThat(d.createStatement().executeUpdate("INSERT INTO wb.ord VALUES (5, 1)"))
          .isEqualTo(1);
      assertThat(rows(v, M("SELECT k, tx_version FROM ") + ordMeta + " ORDER BY k"))
          .containsExactly("1/1", "5/1");
      if (mysql) {
        // 186: a NULL or 0 AUTO_INCREMENT key, which MySQL generates, is refused, not left
        // without metadata; nothing is written
        try (PreparedStatement ps =
            d.prepareStatement("INSERT INTO wb.gen (id, x) VALUES (?, 'n')")) {
          ps.setNull(1, java.sql.Types.INTEGER);
          assertRefused(ps::executeUpdate);
        }
        assertRefused(
            () -> d.createStatement().executeUpdate("INSERT INTO wb.gen (id, x) VALUES (0, 'z')"));
        assertThat(rows(v, "SELECT COUNT(*) FROM wb.gen WHERE x IN ('n', 'z')"))
            .containsExactly("0");
        // 218: nor does the read-back by 0 find an older row with key 0, as a restore stores it
        String genMeta = "wb." + Q(catalog.lookup(List.of(), N("wb"), N("gen")).metadataTable());
        e.execute(
            v,
            "SET SESSION sql_mode = CONCAT(@@sql_mode, ',NO_AUTO_VALUE_ON_ZERO')",
            "INSERT INTO wb.gen (id, x) VALUES (0, 'old')",
            "SET SESSION sql_mode = REPLACE(@@sql_mode, 'NO_AUTO_VALUE_ON_ZERO', '')");
        try (PreparedStatement ps =
            d.prepareStatement("INSERT INTO wb.gen (id, x) VALUES (?, 'z')")) {
          ps.setInt(1, 0);
          assertRefused(ps::executeUpdate);
        }
        assertRefused(
            () -> d.createStatement().executeUpdate("INSERT INTO wb.gen (id, x) VALUES (0, 'z')"));
        assertThat(rows(v, "SELECT COUNT(*) FROM wb.gen WHERE x = 'z'")).containsExactly("0");
        assertThat(rows(v, "SELECT COUNT(*) FROM " + genMeta + " WHERE id = 0"))
            .containsExactly("0");
        e.execute(v, "DELETE FROM wb.gen WHERE id = 0");
        // 186: a key compared after conversion that matches another row
        assertRefused(
            () -> d.createStatement().executeUpdate("INSERT INTO wb.vk (k, x) VALUES (1, 1)"));
        assertThat(rows(v, M("SELECT k, tx_version FROM ") + vkMeta)).containsExactly("01/1");
        assertThat(d.createStatement().executeUpdate("INSERT INTO wb.vk (k, x) VALUES ('1', 1)"))
            .isEqualTo(1);
        // 187: an expression key, and an AUTO_INCREMENT column that is not the key
        assertRefused(
            () ->
                d.createStatement()
                    .executeUpdate("INSERT INTO wb.gen (id, x) VALUES (70 + 0, 'e')"));
        assertRefused(() -> d.createStatement().executeUpdate("INSERT INTO wb.seq (x) VALUES (9)"));
        assertThat(rows(v, "SELECT COUNT(*) FROM wb.seq")).containsExactly("0");
      }
      // 192: a FLOAT key matches its own row
      assertThat(d.createStatement().executeUpdate("UPDATE wb.fl SET x = 2 WHERE x = 0"))
          .isEqualTo(1);
      assertThat(d.createStatement().executeUpdate("DELETE FROM wb.fl WHERE x >= 0")).isEqualTo(1);
      // 195: a comment holding "from" before a created table's name
      d.createStatement().executeUpdate("INSERT INTO wb.made (id, x) VALUES (90, 'f')");
      assertThat(
              d.createStatement()
                  .executeUpdate("DELETE FROM /* from cache */ wb.made WHERE id = 90"))
          .isEqualTo(1);
      d.setAutoCommit(false);
      // 189: whitespace in the clause; a statement ending in ; the split read refuses everywhere
      assertThat(rows(d, "SELECT x FROM wb.imp WHERE id = 1 FOR  UPDATE\n  NOWAIT"))
          .containsExactly("a");
      assertRefused(() -> rows(d, "SELECT x FROM wb.imp WHERE id = 1 FOR UPDATE;"));
      d.rollback();
      if (engine == Engine.MARIADB) {
        for (String wait : List.of("NOWAIT", "SKIP LOCKED")) {
          assertThat(rows(d, "SELECT x FROM wb.imp WHERE id = 1 LOCK IN SHARE MODE " + wait))
              .containsExactly("a");
          d.rollback();
        }
        // 194: a comment after the clause
        assertThat(rows(d, "SELECT x FROM wb.imp WHERE id = 1 LOCK IN SHARE MODE /* c */"))
            .containsExactly("a");
        d.rollback();
      }
      if (engine != Engine.POSTGRESQL && engine != Engine.ORACLE) {
        // 189: the driver's own mark in a literal is refused, never replaced; PostgreSQL and
        // Oracle keep the clause where it is written, and use no mark
        assertRefused(
            () ->
                rows(
                    d,
                    "SELECT x FROM wb.imp WHERE x <> '/* scalardb_native_lock */' AND id = 1"
                        + " FOR UPDATE"));
        d.rollback();
      }
      if (engine != Engine.POSTGRESQL) {
        // 191: FOR NO KEY UPDATE is PostgreSQL's
        assertRefused(() -> rows(d, "SELECT x FROM wb.imp WHERE id = 1 FOR NO KEY UPDATE"));
        d.rollback();
      }
      if (engine == Engine.MYSQL || engine == Engine.MARIADB) {
        // 190: with derived tables neither merged nor given the predicate, still one row locked
        e.execute(
            d,
            engine == Engine.MYSQL
                ? "SET SESSION optimizer_switch = 'derived_merge=off,derived_condition_pushdown=off'"
                : "SET SESSION optimizer_switch = 'derived_merge=off,condition_pushdown_for_derived=off'");
        assertThat(rows(d, "SELECT x FROM wb.imp WHERE id = 1 FOR UPDATE")).containsExactly("a");
        e.execute(v, "SET SESSION innodb_lock_wait_timeout = 1");
        assertThat(v.createStatement().executeUpdate("UPDATE wb.imp SET x = x WHERE id = 2"))
            .isEqualTo(1);
        d.rollback();
      }
      if (engine != Engine.POSTGRESQL) {
        // 196: a write that fails part way is undone to its start, and the transaction goes on
        assertThatThrownBy(
                () ->
                    d.createStatement()
                        .executeUpdate(
                            "UPDATE wb.nn SET v = CASE WHEN id = 2 THEN NULL ELSE 1 END"))
            .isInstanceOf(SQLException.class);
        assertThat(d.createStatement().executeUpdate("UPDATE wb.nn SET v = 5 WHERE id = 2"))
            .isEqualTo(1);
        d.commit();
        assertThat(rows(v, "SELECT id, v FROM wb.nn ORDER BY id")).containsExactly("1/0", "2/5");
        String nnMeta = "wb." + Q(catalog.lookup(List.of(), N("wb"), N("nn")).metadataTable());
        assertThat(rows(v, M("SELECT id, tx_version FROM ") + nnMeta + " WHERE id = 1"))
            .containsExactly("1/1");
      }
      d.setAutoCommit(true);
    }
    if (engine == Engine.MYSQL || engine == Engine.MARIADB) {
      // 193: useAffectedRows on, whichever way it is set, is refused at connect
      Properties on = new Properties();
      on.setProperty("useAffectedRows", "true");
      assertThatThrownBy(() -> e.openDriver(on).close())
          .isInstanceOf(SQLException.class)
          .extracting("SQLState")
          .isEqualTo("08004");
      String url = e.url();
      String driverUrl =
          "jdbc:scalardb-native:"
              + url.substring("jdbc:".length())
              + (url.contains("?") ? "&" : "?")
              + "useAffectedRows=true";
      assertThatThrownBy(
              () -> java.sql.DriverManager.getConnection(driverUrl, e.username(), e.password()))
          .isInstanceOf(SQLException.class)
          .extracting("SQLState")
          .isEqualTo("08004");
    }
  }

