package com.scalar.db.nativejdbc.samples.jdbc;

import edu.umd.cs.findbugs.annotations.SuppressFBWarnings;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.SQLTransactionRollbackException;
import java.util.Optional;
import javax.sql.DataSource;

/**
 * A plain JDBC application over a ScalarDB table, as it would be written for the database itself:
 * the database generates the key, a version column guards against lost updates, and a transfer runs
 * in one transaction. Nothing in it knows about ScalarDB; the driver keeps it consistent with
 * ScalarDB's own transactions on the same table, and a conflict with one comes back as a {@link
 * SQLTransactionRollbackException} with SQLState 40001, which {@link #transfer} retries.
 */
@SuppressFBWarnings(
    value = {"SQL_INJECTION_JDBC", "SQL_PREPARED_STATEMENT_GENERATED_FROM_NONCONSTANT_STRING"},
    justification = "the table name is the application's configuration; values are bound")
public final class ItemStore {

  /** An item: its key, name, quantity and version. */
  public static final class Item {
    public final long id;
    public final String name;
    public final int qty;
    public final int version;

    Item(long id, String name, int qty, int version) {
      this.id = id;
      this.name = name;
      this.qty = qty;
      this.version = version;
    }
  }

  private final DataSource dataSource;
  private final String table;

  /**
   * Creates a store over {@code table}, whose columns are {@code id} (generated), {@code name},
   * {@code qty} and {@code version}.
   *
   * @param dataSource connections through the driver, {@code jdbc:scalardb-native:...}
   * @param table the table, qualified as the application names it
   */
  @SuppressFBWarnings(
      value = "EI_EXPOSE_REP2",
      justification = "the pool is shared by design: the store borrows its connections")
  public ItemStore(DataSource dataSource, String table) {
    this.dataSource = dataSource;
    this.table = table;
  }

  /**
   * Adds an item, its key generated by the database.
   *
   * @return the key
   * @throws SQLException a database error
   */
  public long add(String name, int qty) throws SQLException {
    try (Connection c = dataSource.getConnection();
        PreparedStatement ps =
            c.prepareStatement(
                "INSERT INTO " + table + " (name, qty, version) VALUES (?, ?, 1)",
                new String[] {"id"})) {
      ps.setString(1, name);
      ps.setInt(2, qty);
      ps.executeUpdate();
      try (ResultSet keys = ps.getGeneratedKeys()) {
        if (!keys.next()) {
          throw new SQLException("no key generated");
        }
        return keys.getLong(1);
      }
    }
  }

  /**
   * Reads an item.
   *
   * @return the item, or empty when there is none
   * @throws SQLException a database error
   */
  public Optional<Item> find(long id) throws SQLException {
    try (Connection c = dataSource.getConnection()) {
      return find(c, id);
    }
  }

  private Optional<Item> find(Connection c, long id) throws SQLException {
    try (PreparedStatement ps =
        c.prepareStatement("SELECT id, name, qty, version FROM " + table + " WHERE id = ?")) {
      ps.setLong(1, id);
      try (ResultSet rs = ps.executeQuery()) {
        return rs.next()
            ? Optional.of(new Item(rs.getLong(1), rs.getString(2), rs.getInt(3), rs.getInt(4)))
            : Optional.empty();
      }
    }
  }

  /**
   * Sets an item's quantity if it is still at the version the caller read: optimistic locking.
   *
   * @return whether it was; false when another writer changed it first
   * @throws SQLException a database error
   */
  public boolean setQty(Item read, int qty) throws SQLException {
    try (Connection c = dataSource.getConnection();
        PreparedStatement ps =
            c.prepareStatement(
                "UPDATE "
                    + table
                    + " SET qty = ?, version = version + 1 WHERE id = ? AND version = ?")) {
      ps.setInt(1, qty);
      ps.setLong(2, read.id);
      ps.setInt(3, read.version);
      return ps.executeUpdate() == 1;
    }
  }

  /**
   * Moves {@code qty} from one item to another in one transaction, retried a few times on a
   * conflict (SQLState 40001). Fails, and changes nothing, when the source has too little.
   *
   * @throws SQLException a database error, or a conflict that the retries did not get past
   */
  public void transfer(long from, long to, int qty) throws SQLException {
    for (int attempt = 1; ; attempt++) {
      try (Connection c = dataSource.getConnection()) {
        c.setAutoCommit(false);
        try {
          move(c, to, qty);
          move(c, from, -qty);
          // checked after both writes, so that a failure has something to roll back
          int left = find(c, from).orElseThrow(() -> new SQLException("no item " + from)).qty;
          if (left < 0) {
            throw new SQLException("item " + from + " has too little");
          }
          c.commit();
          return;
        } catch (SQLException | RuntimeException e) {
          // rolled back before autocommit is restored, which would commit what is pending
          c.rollback();
          if (!(e instanceof SQLException)
              || !"40001".equals(((SQLException) e).getSQLState())
              || attempt == 3) {
            throw e;
          }
        } finally {
          c.setAutoCommit(true);
        }
      }
    }
  }

  private void move(Connection c, long id, int delta) throws SQLException {
    try (PreparedStatement ps =
        c.prepareStatement(
            "UPDATE " + table + " SET qty = qty + ?, version = version + 1 WHERE id = ?")) {
      ps.setInt(1, delta);
      ps.setLong(2, id);
      if (ps.executeUpdate() != 1) {
        throw new SQLException("no item " + id);
      }
    }
  }

  /**
   * Removes an item.
   *
   * @return whether there was one
   * @throws SQLException a database error
   */
  public boolean remove(long id) throws SQLException {
    try (Connection c = dataSource.getConnection();
        PreparedStatement ps = c.prepareStatement("DELETE FROM " + table + " WHERE id = ?")) {
      ps.setLong(1, id);
      return ps.executeUpdate() == 1;
    }
  }
}
